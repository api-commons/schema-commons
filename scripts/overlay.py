"""Write an OpenAPI Overlay per standard a context is measured against: overlays/<std>.overlay.yml.

The common OpenAPI stays what the market measured. The overlay is the bridge to the standard:
applied, it marks each schema with the standard object it corresponds to, a map from each
commons property to the standard's field (x-commons-standard.fields), and the standard's
fields the commons does not carry. (The schemas are $refs to schema/*.json, so the map sits on
the schema, not on each property.) Nothing is renamed -- a reader who wants the standard's names has them
beside the commons names. Built from standards/<std>.yml, which standard-pass.py writes.

Usage, from the context's directory: overlay.py"""
from pathlib import Path
import yaml

HUB = Path(__file__).resolve().parent.parent
cfg = yaml.safe_load(open("concepts.yml"))
spec = yaml.safe_load(open("openapi.yml"))
schemas = spec["components"]["schemas"]
title = lambda c: "".join(w.capitalize() for w in c.split("_"))
written = []
for std in cfg.get("standards") or []:
    p = Path("standards") / f"{std['standard']}.yml"
    if not p.exists():
        continue
    measured = yaml.safe_load(open(p))
    actions = []
    for concept, m in (measured.get("concepts") or {}).items():
        name = title(concept)
        if name not in schemas:
            continue
        actions.append({"target": f"$.components.schemas.{name}",
                        "update": {"x-commons-standard": {"standard": std["standard"], "source": measured["source"],
                                                          "objects": m["objects"],
                                                          "core_coverage": m.get("core_coverage"),
                                                          "fields": m.get("crosswalk") or {},
                                                          "standard_only": m.get("standard_only") or []}}})
    if not actions:
        continue
    out = {"overlay": "1.0.0",
           "info": {"title": f"{cfg['name']} -- {std['standard']} alignment",
                    "version": spec["info"]["version"],
                    "description": f"Marks the common {cfg['name']} OpenAPI with the {std['standard']} object each schema "
                                   "corresponds to, and the field each property maps to. Generated by scripts/overlay.py from "
                                   f"standards/{std['standard']}.yml; nothing is renamed."},
           "extends": "openapi.yml", "actions": actions}
    Path("overlays").mkdir(exist_ok=True)
    yaml.safe_dump(out, open(f"overlays/{std['standard']}.overlay.yml", "w"), sort_keys=False, width=120)
    written.append(f"{std['standard']} ({len(actions)} actions)")
print("overlays:", ", ".join(written) or "none")
